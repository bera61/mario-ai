def make_sprite(rows, colors):
    width = max(len(row) for row in rows)
    surface = pygame.Surface((width, len(rows)), pygame.SRCALPHA)
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            if char != ".":
                surface.set_at((x, y), colors[char])
    return surface
